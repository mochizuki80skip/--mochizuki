// 投稿テーマとテンプレート。AI を使わない場合の下書きと、AI への指示の両方に使う。
const SEASON_TOPICS = {
  1: "寒さによる肩・首のこわばりやぎっくり腰",
  2: "寒さと冷えによる腰まわりの負担",
  3: "新生活に向けた姿勢と身体の準備",
  4: "新生活の疲れやデスクワークによる首・肩の負担",
  5: "気温差による身体のだるさと運動再開時のケガ",
  6: "梅雨時期の身体の重さや関節の違和感",
  7: "冷房による冷えと夏の運動時のケガ",
  8: "夏の疲れと冷房による身体のこわばり",
  9: "季節の変わり目の身体の不調と秋のスポーツ",
  10: "朝晩の冷え込みによる寝違えや腰の負担",
  11: "寒さによる筋肉のこわばりと転倒によるケガ",
  12: "年末の忙しさによる疲れと大掃除での腰の負担",
};

const THEMES = [
  { id: "season", label: "季節の身体のケア" },
  { id: "symptom", label: "症状の解説（ぎっくり腰・寝違え等）" },
  { id: "selfcare", label: "自宅でできるセルフケア" },
  { id: "sports", label: "スポーツのケガ・部活" },
  { id: "traffic", label: "交通事故のケガ" },
  { id: "info", label: "営業時間・休診のお知らせ" },
  { id: "campaign", label: "キャンペーン・メニュー紹介" },
  { id: "staff", label: "スタッフ・院内の紹介" },
];

function buildTemplate(themeId, memo, s, date = new Date()) {
  const name = s.name || "当院";
  const area = s.area ? `${s.area}の` : "";
  const season = SEASON_TOPICS[date.getMonth() + 1];
  const note = memo ? `\n\n${memo}` : "";
  const footer = s.footer ? `\n\n${s.footer}` : "";

  const bodies = {
    season: `【${date.getMonth() + 1}月の身体のケア】\nこの時期は${season}を感じる方が増えてきます。${note}\n\n${area}${name}では、お一人おひとりの状態を確認したうえで、施術とご自宅でのケアのアドバイスを行っています。気になる症状がある方はお気軽にご相談ください。`,
    symptom: `【症状のお話】${note || "\n\n急な腰の痛みや首が回らないといった症状は、無理に動かすと負担が大きくなることがあります。"}\n\n痛みが出たときは無理をせず、早めにご相談ください。${area}${name}では状態を丁寧に確認し、施術とご自宅での過ごし方をお伝えしています。`,
    selfcare: `【ご自宅でできるセルフケア】${note || "\n\n長時間同じ姿勢が続いたときは、1時間に1回ほど立ち上がって肩を回すなど、身体を軽く動かすことを意識してみてください。"}\n\n痛みが強いときは無理に行わず、${name}へご相談ください。`,
    sports: `【スポーツのケガについて】${note || "\n\n捻挫や打撲、肉離れなどスポーツ中のケガは、早めの処置と適切なケアが大切です。"}\n\n${area}${name}では、部活動や趣味でスポーツをされている方のケガの施術と、競技復帰に向けたアドバイスを行っています。`,
    traffic: `【交通事故のケガについて】${note || "\n\n交通事故の直後は痛みが出にくく、数日たってから首や腰に症状が出ることがあります。"}\n\n${name}では、交通事故によるケガの施術と、保険会社とのやりとりについてのご相談を承っています。まずはお気軽にお問い合わせください。`,
    info: `【お知らせ】${note || "\n\n営業日・受付時間についてのお知らせです。"}\n\nご不便をおかけしますが、よろしくお願いいたします。`,
    campaign: `【メニューのご案内】${note || "\n\n（メニュー名・内容・料金・期間を記入してください）"}\n\n内容や料金、期間などの詳細はお気軽にお問い合わせください。`,
    staff: `【${name}のご紹介】${note || "\n\n（スタッフや院内の様子を記入してください）"}\n\n初めての方も安心してお越しいただけるよう、丁寧な説明を心がけています。`,
  };
  return (bodies[themeId] || bodies.season) + footer;
}

function buildAiPrompt(themeId, memo, s, date = new Date()) {
  const theme = THEMES.find((t) => t.id === themeId)?.label ?? "季節の身体のケア";
  return `あなたは接骨院の Google ビジネスプロフィール（GBP）の投稿文を書くアシスタントです。
以下の条件で投稿文を 1 つだけ書いてください。前置きや説明は不要で、本文のみを出力してください。

# 院の情報
- 院名：${s.name || "（未設定）"}
- 地域：${s.area || "（未設定）"}
- 特徴：${s.features || "（未設定）"}

# 投稿の条件
- テーマ：${theme}
- 時期：${date.getMonth() + 1}月（この時期に多い悩み：${SEASON_TOPICS[date.getMonth() + 1]}）
- 補足：${memo || "なし"}
- 250〜400 文字程度。冒頭に【】付きの短い見出し。地域名と院名を自然に 1 回ずつ入れる
- 絵文字は使わないか、使っても 1〜2 個まで
- 本文に電話番号・URL は書かない

# 必ず守ること（柔道整復師法・医療広告ガイドライン・景品表示法）
- 「治る」「完治」「必ず」「絶対」「100%」など効果を断定・保証する表現を使わない
- 「No.1」「地域一」「最高」など比較・最上級の表現を使わない
- 患者の体験談や施術前後の比較を書かない
- 肩こりや慢性的な症状に健康保険が使えるような書き方をしない
- 不安をあおる書き方をしない
${s.footer ? `\n最後に次の文をそのまま入れてください：\n${s.footer}` : ""}`;
}
